// Converts the curated RASP .eng files in data/eng/ into src/data/motors.generated.js
// Run: npm run build:motors
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATALOG } from './motor-catalog.mjs';
import { parseEng, curveStats, impulseClass } from '../src/physics/eng.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const engDir = path.join(root, 'data/eng');

// Estes colour-codes motor labels: green = booster (-0), purple = upper stage
// (longest delay of a class), red = single stage.
const ESTES_UPPER = new Set(['A8-5', 'B6-6', 'C6-7', 'C11-7', 'D12-7', 'E9-8', 'E12-8', 'E16-8', 'F15-8']);
const DELAY_GRAIN_G_PER_S = { 13: 0.25, 18: 0.6, 24: 1.0, 29: 1.6 };
const EJECTION_G = { 13: 0.4, 18: 1.0, 24: 1.6, 29: 2.4 };

function nominalDelay(str) {
  const d = String(str).split(/[-,]/).map(Number).filter((x) => Number.isFinite(x) && x > 0 && x < 50);
  if (!d.length) return 0;
  d.sort((a, b) => a - b);
  return d[Math.floor(d.length / 2)];
}

const curves = {};
const motors = [];

function loadCurve(file, mfr) {
  const eng = parseEng(fs.readFileSync(path.join(engDir, file), 'utf8'));
  const id = file.replace(/\.eng$/, '');
  const stats = curveStats(eng.points);
  curves[id] = {
    id,
    mfr,
    diameter: eng.diameter,
    length: eng.length,
    propMass: eng.propMass,
    totalMass: eng.totalMass,
    headerDelays: eng.delays,
    points: eng.points.map(([t, f]) => [+t.toFixed(4), +f.toFixed(3)]),
    impulse: +stats.impulse.toFixed(3),
    source: 'thrustcurve.org certification data (via github.com/openrocket/motor-database), file ' + file,
    notes: eng.comments.filter(Boolean).slice(0, 6).join(' '),
  };
  return curves[id];
}

for (const c of CATALOG) {
  const base = loadCurve(c.file, c.mfr);
  const overrides = {};
  for (const [d, o] of Object.entries(c.delayFiles || {})) overrides[d] = loadCurve(o.file, c.mfr);
  const dia = Math.round(base.diameter);
  const baseDelay = c.baseIsBooster ? 0 : nominalDelay(base.headerDelays);
  const baseHasEjection = !c.baseIsBooster && !/^(P|100)$/i.test(base.headerDelays.trim()) && baseDelay > 0;
  for (const d of c.delays) {
    const curve = overrides[d] || base;
    const plugged = d === 'P';
    const delayNum = plugged ? null : d;
    let mass = curve.totalMass * 1000; // grams
    if (curve === base && c.mfr === 'Estes' && !c.propellant) {
      // Adjust case mass for the delay grain and ejection charge of this variant.
      const perS = c.massPerDelay ?? DELAY_GRAIN_G_PER_S[dia] ?? 0.6;
      const ej = EJECTION_G[dia] ?? 1;
      const hasEj = !plugged && delayNum > 0;
      mass += perS * ((delayNum || 0) - baseDelay);
      mass += (hasEj ? ej : 0) - (baseHasEjection ? ej : 0);
    }
    const designation = `${c.common}-${plugged ? 'P' : d}${c.suffix}`;
    let usage = 'single';
    if (plugged) usage = 'plugged';
    else if (delayNum === 0) usage = 'booster';
    else if (c.mfr === 'Estes' && ESTES_UPPER.has(`${c.common}-${d}`)) usage = 'upper';
    const propellant = c.propellant || 'Black powder';
    motors.push({
      id: `${c.mfr}-${designation}`.replace(/\//g, '_'),
      mfr: c.mfr,
      designation,
      common: c.common,
      cls: impulseClass(curve.impulse),
      curve: curve.id,
      delay: delayNum,
      plugged,
      usage,
      propellant,
      blackPowder: propellant === 'Black powder',
      diameter: curve.diameter,
      length: curve.length,
      propMass: +(curve.propMass * 1000).toFixed(2),
      totalMass: +mass.toFixed(2),
    });
  }
}

const out = `// AUTO-GENERATED by tools/build-motors.mjs — do not edit by hand.
// Thrust curves: NAR/CAR/TRA certification data as published on thrustcurve.org,
// mirrored at https://github.com/openrocket/motor-database. Masses in grams,
// dimensions in millimetres, curve points are [seconds, newtons].
export const CURVES = ${JSON.stringify(curves, null, 0)};

export const MOTORS = ${JSON.stringify(motors, null, 1)};
`;
fs.writeFileSync(path.join(root, 'src/data/motors.generated.js'), out);
console.log(`Wrote ${Object.keys(curves).length} curves, ${motors.length} motor variants`);
for (const m of motors) console.log(m.designation.padEnd(10), m.mfr.padEnd(9), m.usage.padEnd(8), (m.totalMass + 'g').padStart(8), curves[m.curve].impulse.toFixed(2) + 'Ns');
